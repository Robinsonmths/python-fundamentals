# Faça um programa que calcule a área de
# um quadrado, em seguida mostre o dobro
# desta área para o usuário.

# Passo 1: Pedir o lado e calcular a área
lado = float(input("Digite o tamanho do lado do quadrado: "))
area = lado * lado
# Passo 2: Calcular o dobro da área
dobro = area * 2
# Mostrar o resultado
print(f"A área é {area} e o dobro dela é {dobro}")
