numero = int(input('Digite um número de 1 a 7: '))
if numero == 1:
  print(f'Segunda')
elif numero == 2:
  print(f'Terça')
elif numero == 3:
  print(f'Quarta')
elif numero == 4:
  print(f'Quinta')
elif numero == 5:
  print(f'Sexta')
elif numero == 6:
  print(f'Sábado')
elif numero == 7:
  print(f'domingo')
else:
  print(f'valor inválido')